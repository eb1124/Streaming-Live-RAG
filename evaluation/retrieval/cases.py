"""Authored retrieval benchmark cases. Source of truth for evaluation/retrieval/queries.jsonl.

Each case names the evidence needed to answer it, as verbatim quotes from the corpus. `build.py`
resolves each quote to the one chunk (in the named document) that contains it and freezes the
chunk ids into queries.jsonl. Nothing here was chosen by looking at what any model retrieves.

A case has one or more evidence *units* (facts the answer needs). A unit has one or more acceptable
sources: the same fact stated in several chunks (e.g. identical text in both UConn procedure
versions, or a rule repeated in the UConn policy and its procedures). A unit is found when any of
its sources is retrieved.

Document keys (DOCS below) are short names for doc_ids.
Question types: direct_fact, paraphrase, conditional, exception, numeric_threshold, terminology,
clause_specific, cross_section, version_sensitive.
"""


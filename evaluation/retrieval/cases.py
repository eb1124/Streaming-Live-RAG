def src(doc: str, evidence: str) -> dict:
    return {"doc": doc, "evidence": evidence}


def unit(*sources: dict) -> list[dict]:
    return list(sources)


# Identical text in both UConn procedure versions: either version answers a version-neutral question.
def both_uconn(evidence: str) -> list[dict]:
    return unit(src("uconn_feb", evidence), src("uconn_jul", evidence))


